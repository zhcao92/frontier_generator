#!/usr/bin/env python3
"""Coverage-aware DETR: predicts frontier position + normalised opinion increase.

Trained from the coverage dataset (step_{fid}.json files) generated by the
geometric pipeline.  Adds a score head that predicts the normalised opinion
increase (marginal_gain / total_marginal_gain from greedy selection) for each
frontier candidate.

Usage:
    python models/coverage_detr_model.py prepare \
        --coverage-dir results/coverage_dataset \
        --out cov_detr_cache --min-id 29 --max-id 5000
    python models/coverage_detr_model.py train \
        --data cov_detr_cache --save-dir cov_detr_checkpoints \
        --epochs 200 --batch-size 32 --lr 1e-4 \
        --split-id 1500 --lambda-score 2.0
    python models/coverage_detr_model.py predict \
        --frontier-id 7000 --checkpoint cov_detr_cache/model_best.pt \
        --coverage-dir results/coverage_dataset
"""

