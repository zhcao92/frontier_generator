def main():
    parser = argparse.ArgumentParser(
        description='Coverage-aware DETR: position + score prediction')
    sub = parser.add_subparsers(dest='command')

    # prepare
    p = sub.add_parser('prepare', help='Pre-compute coverage DETR dataset')
    p.add_argument('--coverage-dir', required=True,
                   help='Coverage dataset directory (with manifest.json)')
    p.add_argument('--out', default='cov_detr_cache',
                   help='Output cache directory')
    p.add_argument('--min-id', type=int, default=None,
                   help='Min frontier ID (inclusive)')
    p.add_argument('--max-id', type=int, default=None,
                   help='Max frontier ID (inclusive)')

    # train
    p = sub.add_parser('train', help='Train coverage DETR model')
    p.add_argument('--data', default='cov_detr_cache')
    p.add_argument('--save-dir', default=None,
                   help='Checkpoint save directory (default: --data dir)')
    p.add_argument('--epochs', type=int, default=200)
    p.add_argument('--batch-size', type=int, default=32)
    p.add_argument('--lr', type=float, default=1e-4)
    p.add_argument('--split-id', type=int, default=1500)
    p.add_argument('--lambda-score', type=float, default=LAMBDA_SCORE)
    p.add_argument('--weight-decay', type=float, default=1e-4)
    p.add_argument('--save-every', type=int, default=50)
    p.add_argument('--min-id', type=int, default=None,
                   help='Min frontier ID for training (inclusive)')
    p.add_argument('--max-id', type=int, default=None,
                   help='Max frontier ID for training (inclusive)')

    # predict
    p = sub.add_parser('predict', help='Predict and visualise')
    p.add_argument('--frontier-id', type=int, required=True)
    p.add_argument('--checkpoint', required=True)
    p.add_argument('--coverage-dir', default=None,
                   help='Coverage dataset dir for GT overlay (optional)')
    p.add_argument('--coverage-rate', type=float, default=None,
                   help='Greedy select predictions by score until '
                        'cumulative score >= this value (e.g. 0.8)')
    p.add_argument('--proximity-disq-m', type=float, default=2.0,
                   help='Disqualify unselected predictions within this '
                        'distance (m) of a selected one (default: 2.0)')
